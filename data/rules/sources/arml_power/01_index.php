</li>-->

<li><p align="justify">
Teams for ARML must be drawn from a well defined region. These geographic regions must be contiguous and non-intersecting. Regions with obvious gerrymandering (e.g., a state plus one student in another distant state) are not acceptable. If any student can potentially compete for more than one team, then the region definitions for all affected teams are in error and must be rewritten to resolve such conflicts. The geographic regions can be as small as a single school (as in the case of Phillips Academy and Phillips Exeter), a city, a county, a state, or as large as a collection of states (as in the case of Desert Southwest). Teams wishing to modify the region from which they can draw their team should contact the Executive Director of ARML for approval.</a>. 
</p></li>

<li><p align="justify">Please see the document above titled "Some Mathematical Ideas Used in the Competition" for a complete description of the concepts that are assumed for the ARML competition. Changes are regularly made to this document.</p></li>

<li><p align="justify">Calculators will not be allowed on any part of the ARML contest.</p>
</li>

<li><p align="justify">The scoring structure of the contest will be as follows.</p>

<p align="justify"><b>Individual Rounds.</b> The Individual Rounds consist of five rounds, each with two questions.  One point is awarded for each question answered correctly for a total of 10 points possible per person and 150 points possible per team.</p>
<p align="justify"><b>Team Round.</b> The Team Round consists of ten questions.  Each correct answer is awarded five points for a total of 50 possible points per team.</p>
<p align="justify"><b>Power Round.</b> The Power Round is worth 50 points.</p>
<p align="justify"><b>Relay Round.</b> A correct answer submitted in three minutes will be awarded five points; a  correct answer submitted in six minutes will be awarded three points. Thus, there are 25 points possible per team for Relay 1 and 25 points possible per team for Relay 2. </p>
</li>

<li><p align="justify">Team score ties are broken by considering the sum of the Team and Power Rounds, then the Relay Round total, and then the Individual Round total.</p></li>

<li><p align="justify">No substitutions can be made once the Team Round has started. All substitutions must be reported to the Head of the Scoring Room or the Site Chairperson prior to the beginning of the Team Round.
</p></li>

<li><p align="justify">If a team arrives at the meet with fewer than 15 members, they can participate as a team.  During the Relay Round the team would form as many complete three person teams as possible.  If a team is short one member then the two students will receive only questions two and three.  If they are short two members then the single member will receive only question three.  Should these abbreviated teams have the correct answer, they will get credit for it.</p>
</li>

<li><p align="justify">Should a pre-registered student arrive late for any reason, he/she may join the team on which he/she is registered during the next official break in the meet.  (Between the Team and Power rounds, before the beginning of any Individual round, before the beginning of either Relay round.)</p>
</li>

<li><p align="justify">The use of "borrowed" students is prohibited.  No student can participate on a team he/she is not registered with for housing.</p>
</li>

<li><p align="justify">No teams can be added to the competition later than 15 days prior to the Friday the meet begins.</p>
</li>

<li><p align="justify">Use of a dictionary in book form will be allowed for participants whose first language is not English.  Electronic dictionaries or translators are not allowed.</p>
</li>

<li><p align="justify">Use of a visual aid such as a magnifying glass is allowed for participants with a visual handicap.  These must be inspected prior to the beginning of the Team round by the Team proctor.  If any question arises as to the legitimacy of the device, the Site Chairperson will have the final word.</p>
</li>

<li><p align="justify">During the Individual round there is to be absolutely no communication between students once the questions are handed out.</p>
</li>

<li><p align="justify"><p align="justify">The procedures for the Relay Round are very specific.  Please review the next rule below for a complete description of the Relay Round.  </li></p>

<li><p align="justify">During the Relay round only the answer to the question in the student's possession can be passed on to the next person on the team.  The answer may be underlined to show orientation but that is the only mark that can be on the paper.  The method of passing of answer(s) should, in no way, indicate anything besides the answer to the question.  No comments or any other information may be communicated at any time during the Relay round. In the past, we have found that ARML participants have devised methods to communicate with members of their team. These practices are violations of the rules of the competition. Such practices include, but are not limited to: passing back multiple pieces of paper with the same answer at the same time in an effort to communicate that the participant is very certain of his/her computation, or a participant audibly crumpling and/or throwing a piece of paper on the floor to communicate to another participant that his/her submitted answer cannot be used in subsequent problems. Participants may underline answers so that they will be read correctly, to distinguish between a 6 and a 9, for example.  In the spirit of fair and honest competition, and so that all individual teams are competing on the same playing field, we hope that all participants will abide by the rules as they were originally intended.  Relay teams that are found to be communicating more than the answer to the problem will possibly face disqualification.  Specific penalties will be decided by the ARML officials.</p>
</li>

<li><p align="justify">Once seated, Relay teams will remain unchanged until the end of regular competition.</p>
</li>

<li><p align="justify">Teams can ONLY submit exactly one solution to the Power Question. If additional solutions are submitted, then all solutions will be corrected and the team will be assessed the lowest score obtained.</p></li>

<li><p align="justify">Electronic devices are not allowed to be used in any part of the contest. This includes all cell phones, smart phones, computers, tablets, or any other device that used electricity (AC or DC) and has an on/off switch. If such an electronic device is discovered in the room during the Team or Power round then the team will be disqualified from that round. Proctors will collect all electronic devices before the Team round and will return them at the end of the Power round.  Also, all electronic devices must be in the off mode during all other competition and award events.  It is the responsibility of the students to recover their electronic device following the Power round in the event that they were collected by the proctor as required.   </p>
</li>

<li><p align="justify">Students are expected to obey the above rules. They are also expected to respect the property of the University, ARML, and their respective teams. Failure to comply can lead to deletion of those students' scores for the round or disqualification of those involved for the entire competition. If deemed serious enough by the Site Chairperson, Coach, and/or Head Judge, a student may be removed from the premises by a coach, parent,  or guardian.</p> 
</li>

<li><p align="justify">If a student is caught cheating, the repercussions for the current
contest are defined as follows:</p>

<p><ul>
<li>If the cheating instance takes place during the Team or Power
round, the score for that round is nullified.</li>

<li>If the cheating instance takes place during the Individual round,
that student's scores are nullified for all of his/her Individual
rounds.</li>

<li>If the cheating instance takes place during the Relay round, that
student's scores are nullified for his or her three member relay team for both relay rounds.</li>

<li>The student is barred from competing in the remainder of the
competition. The student's relay team will compete with one less
student and those students will occupy positions 2 and 3.</li>

<li>Further disciplinary actions are at the discretion  of the student's
team leaders.</li>
</ul>
</p>
</li>


</ol>



</p>








