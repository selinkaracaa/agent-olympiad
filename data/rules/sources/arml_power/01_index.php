<li><p>A student can not have turned 19 before the December 31 immediately preceding the ARML  Competition. If the student turns 19 between January 1 and the competition dates he/she would be eligible as long as he/she did not graduate high school (K-12) prior to March 1 of the year of the competition. 
No student who graduated high school prior to March 1 of the year of the competition is eligible for ARML in any case.
If you think there are extenuating circumstances please submit them to the ARML Executive Director, and the ARML Board will consider the matter. <!--(This rule was revised in April 2014.)--> </p></li>

