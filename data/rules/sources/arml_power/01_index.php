<h3 align="center">ARML/IRML Competition Rules</h3>

<p align="justify">
<ol>
<li>
<p align="justify">A team will consist of 15 members.  Coaches are expected to gauge the strength of each of the 15 member teams and place their students on the teams accordingly.  The team that consists of the students who have historically performed with the highest results should be placed on the same 15 member team.  The next strongest 15 students should be placed on the next team, etc.  Those teams will then be named, A1, A2, A3, etc. if they are to compete in the A division and B1, B2, B3, etc. if they are to compete in the B division  Please see the section called "Team Names" of the document called, "General Information for All Sites," for clarification. (This rule was revised in April 2017.)</p>
</li>

<li><p align="justify">Each year, regions will be ordered by the highest score achieved by a team in that
region. All teams in the top 20 regions will be required to compete in Division A. The remaining regions may choose the division in which all of their teams will compete. Students on the top teams in each division will receive software and/or book prizes. During the award ceremony, we encourage all students from the same regions as the top teams to come forward to celebrate their team's performance, and we will have additional prizes for these students as well.(This rule was revised in April 2017.)</p></li>

